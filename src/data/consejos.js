const DEFAULT_REVIEWED_AT = '2026-04-28'

const SOURCE_REVIEW_DATES = [
  { token: 'NIDDK', reviewedAt: '2026-04-24' },
  { token: 'NHS', reviewedAt: '2026-04-22' },
  { token: 'WHO', reviewedAt: '2026-04-21' },
  { token: 'International Diabetes Federation', reviewedAt: '2026-04-20' },
  { token: 'Hospital General Universitario Gregorio Maranon', reviewedAt: '2026-04-19' },
]

const getReviewedAtFromSource = (source) => {
  if (typeof source !== 'string' || !source.trim()) return DEFAULT_REVIEWED_AT

  const matchedDates = SOURCE_REVIEW_DATES
    .filter(({ token }) => source.includes(token))
    .map(({ reviewedAt }) => reviewedAt)

  if (!matchedDates.length) return DEFAULT_REVIEWED_AT
  return matchedDates.sort().at(-1)
}

const normalizeConsejoText = (text) =>
  text
    .replace(/\s+([A-ZÁÉÍÓÚÑ][A-ZÁÉÍÓÚÑ0-9\s(),.-]{2,}:)/g, '\n\n$1')
    .replace(/\s+(\d{1,2}[.-])/g, '\n$1')
    .replace(/\s{2,}/g, ' ')
    .trim()

